		System.out.println("str2 : " + str2);
		
		// ""/ null 비교
		// 화장실에 갔는데 휴지심은 있고 휴지가 없는 상태 > ""
		// 휴지심 조차도 없는 경우 > null
		 
		int [] num = {0,1,2,3};
		
		System.out.println(num);
		
		
		
		
		
		
